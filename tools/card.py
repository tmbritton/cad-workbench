#!/usr/bin/env python
"""Regenerate the block of measured facts in each project's README.

    mise card                    # every project
    mise card dehydrator-riser   # one

A project README is written by hand and should stay that way: what the part is
for, why a dimension is what it is, what was tried and rejected. But some of
what belongs in it can only come from building the thing — how big it turned
out, how many bodies, what it weighs, what the printability rules said — and a
hand-maintained table of those drifts from the code the first time anything
moves. It drifts silently, which is worse: a stale number reads exactly like a
fresh one.

So they are generated, into a marked block the rest of the file leaves alone:

    <!-- AUTO: regenerated by `mise card`. Do not hand-edit. -->
    ...
    <!-- /AUTO -->

No timestamp in it, deliberately. A timestamp means every run produces a diff
and the block becomes noise in every commit; without one, `git diff` after
`mise card` is empty unless the geometry actually changed, which makes the
command safe to run on reflex and its output worth reading when it is not.

Slicing is off by default because it takes a minute a project; `--slice` adds
the real time and weight to the table.
"""

from __future__ import annotations

import argparse
import re
import sys
import traceback
from pathlib import Path

from cadkit import dfm, measure, slicing
from cadkit.discover import is_model, load, model_files, project_path, projects
from cadkit.export import GREEN, GREY, OFF, PROJECTS, RED, build_model, material_of

OPEN = "<!-- AUTO: regenerated by `mise card`. Do not hand-edit. -->"
CLOSE = "<!-- /AUTO -->"
BLOCK = re.compile(re.escape(OPEN) + r".*?" + re.escape(CLOSE), re.S)

HEADING = "## As built"


def as_built(project: Path, want_slice: bool) -> tuple[list[dict], list[str]]:
    """Build every model in a project and collect what only building can tell."""
    rows: list[dict] = []
    notes: list[str] = []

    with project_path(project):
        for path in model_files(project):
            try:
                module = load(path.stem)
            except Exception:
                notes.append(f"{path.stem}: import failed")
                continue
            if not is_model(module):
                continue

            material = material_of(module)
            try:
                result = build_model(
                    project=project.name,
                    name=path.stem,
                    build_fn=module.build,
                    check_fn=getattr(module, "check", None),
                    material=material,
                    rules=dfm.RULES,
                    allow=getattr(module, "ALLOW", None),
                )
            except FileNotFoundError as missing:
                notes.append(
                    f"{path.stem}: needs geometry this checkout lacks ({missing})"
                )
                continue
            except Exception as exc:
                notes.append(f"{path.stem}: {type(exc).__name__}: {exc}")
                continue

            box = result.part.bounding_box().size
            row = {
                "name": path.stem,
                "size": f"{box.X:.1f} x {box.Y:.1f} x {box.Z:.1f}",
                "volume": f"{result.volume / 1000:.1f}",
                "solids": result.solids,
                "material": material.name if material else "",
                "mass": f"{material.mass(result.volume):.0f}" if material else "",
                "findings": result.findings,
                "print": "",
            }

            if want_slice and material and material.filament:
                try:
                    cut = slicing.slice_stl(
                        result.stl,
                        material,
                        slicing.workdir_for(project.name, path.stem),
                        support=bool(getattr(module, "SUPPORT", False)),
                        findings=result.findings,
                        extra=(
                            slicing.brim(getattr(module, "BRIM", 0))
                            if getattr(module, "BRIM", 0)
                            else None
                        ),
                    )
                    row["print"] = f"{cut.duration}, {cut.grams:.0f} g"
                except slicing.SlicerError as exc:
                    notes.append(f"{path.stem}: not sliced ({exc})")

            rows.append(row)
    return rows, notes


def render_block(
    rows: list[dict], notes: list[str], want_slice: bool, unverified=()
) -> str:
    """The AUTO block's contents. Pure: same inputs in, same text out."""
    if not rows:
        return f"{OPEN}\n\nNothing in this project builds on this checkout.\n\n{CLOSE}"

    mass = any(r["mass"] for r in rows)
    header = ["Model", "Size (mm)", "Volume (cm3)", "Bodies"]
    if mass:
        header.append("Est. mass")
    if want_slice:
        header.append("Sliced")

    lines = [OPEN, "", "| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for row in rows:
        cells = [
            f"`{row['name']}`",
            row["size"],
            row["volume"],
            str(row["solids"]),
        ]
        if mass:
            cells.append(f"{row['mass']} g {row['material']}".strip())
        if want_slice:
            cells.append(row["print"] or "—")
        lines.append("| " + " | ".join(cells) + " |")

    lines.append("")
    lines.append(
        "Estimated mass is `density x solid volume` and assumes the part is solid "
        "through; the sliced figure, where there is one, is what the slicer says."
        if want_slice
        else "Estimated mass is `density x solid volume` and assumes the part is "
        "solid through. `mise slice` gives the real figure."
    )

    findings = [(r["name"], f) for r in rows for f in r["findings"]]
    lines += ["", "**Printability** (`mise check`)", ""]
    if not findings:
        lines.append("Nothing to report on any model.")
    else:
        for name, finding in findings:
            mark = {"fail": "**fails**", "warn": "warns", "allowed": "allowed"}[
                finding.severity
            ]
            lines.append(f"- `{name}` {mark}: {finding.message}")
            if finding.reason:
                lines.append(f"  - allowed because: {finding.reason}")

    if unverified:
        lines += ["", "**Still provisional** (`measurements.toml`)", ""]
        lines += [f"- `{m.name}` = {m.value:g} mm — {m.how}" for m in unverified]

    if notes:
        lines += ["", "**Not measured**", ""]
        lines += [f"- {note}" for note in notes]

    lines += ["", CLOSE]
    return "\n".join(lines)


def write_card(project: Path, want_slice: bool) -> bool:
    """Returns True if the README changed."""
    readme = project / "README.md"
    if not readme.is_file():
        print(f"  {RED}no README.md in {project.name}{OFF}", file=sys.stderr)
        return False

    rows, notes = as_built(project, want_slice)
    block = render_block(rows, notes, want_slice, measure.provisional(project))
    text = readme.read_text()

    if BLOCK.search(text):
        updated = BLOCK.sub(lambda _: block, text, count=1)
    else:
        # First run on a project: put the block under its own heading at the
        # end, where it does not push anything hand-written down the page.
        updated = text.rstrip("\n") + f"\n\n{HEADING}\n\n{block}\n"

    if updated == text:
        print(f"  {GREY}unchanged{OFF} {project.name}/README.md")
        return False
    readme.write_text(updated)
    print(f"  {GREEN}written{OFF}  {project.name}/README.md  ({len(rows)} models)")
    return True


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__.splitlines()[0],
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="\n".join(__doc__.splitlines()[2:]),
    )
    ap.add_argument("project", nargs="?", help="project folder name; omit for all")
    ap.add_argument(
        "--slice",
        dest="want_slice",
        action="store_true",
        help="also record real print time and weight (slow: a minute a project)",
    )
    args = ap.parse_args()

    available = projects()
    if not available:
        print(f"{RED}no projects found in {PROJECTS}{OFF}", file=sys.stderr)
        return 1
    if args.project:
        chosen = [p for p in available if p.name == args.project]
        if not chosen:
            names = ", ".join(p.name for p in available)
            print(f"{RED}no such project: {args.project}{OFF}", file=sys.stderr)
            print(f"{GREY}available: {names}{OFF}", file=sys.stderr)
            return 1
    else:
        chosen = available

    changed = 0
    for project in chosen:
        try:
            changed += write_card(project, args.want_slice)
        except Exception:
            print(f"  {RED}FAIL{OFF} {project.name}", file=sys.stderr)
            traceback.print_exc()
            return 1

    print(f"\n{changed} README(s) updated, {len(chosen) - changed} unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
